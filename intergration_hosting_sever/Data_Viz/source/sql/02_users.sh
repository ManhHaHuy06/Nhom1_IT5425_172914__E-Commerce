#!/bin/bash
set -e
mysql -uroot -p"$MYSQL_ROOT_PASSWORD" <<SQL
CREATE USER '${OLTP_SIM_USER}'@'%' IDENTIFIED BY '${OLTP_SIM_PASSWORD}';
GRANT SELECT, INSERT, UPDATE, DELETE ON ${MYSQL_DATABASE}.* TO '${OLTP_SIM_USER}'@'%';
CREATE USER '${OLTP_ETL_USER}'@'%' IDENTIFIED BY '${OLTP_ETL_PASSWORD}';
GRANT SELECT ON ${MYSQL_DATABASE}.* TO '${OLTP_ETL_USER}'@'%';
FLUSH PRIVILEGES;
SQL
